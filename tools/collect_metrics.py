"""Re-measure the deterministic figures, read the recorded ones, write docs/metrics.json.

This repository publishes two kinds of number and they have to be checked differently.

The test suite is deterministic: it either passes at the same coverage or it does not, so
its figures are re-measured on every run and a drift breaks the build.

The throughput and latency figures are not. Rerunning a load measurement on a shared
machine produces different numbers, and a checker that re-measured them and demanded they
match would fail at random. A check that fails at random is one everybody learns to
ignore, and then it is not protecting the deterministic figures either. So the timings are
read from the recorded run in docs/experiments, which `make bench` regenerates
deliberately, and the diff then shows exactly which published figures moved. ADR-004 has
the reasoning.

What is re-measured on every run instead is the thing that actually carries the argument:
`tools/check_invariant.py` re-derives the serialised ceiling and checks the recorded
throughput against it, which is a relationship rather than a timing and holds on any
machine.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPERIMENT_DIR = ROOT / "docs" / "experiments"
METRICS_PATH = ROOT / "docs" / "metrics.json"

EXPERIMENTS = ("e1_four_shapes", "e2_concurrency_sweep",
               "e3_how_little_is_too_much", "e4_three_clocks")
CHECKED_DOCUMENTS = ("README.md", "docs/adr/ADR-005-what-this-cannot-measure.md")
TABLE_ANCHOR = ["| {} |"]

ANCHORS: dict[str, list[str]] = {
    "tests_total": ["{} tests"],
    "coverage_line_pct": ["{} percent line coverage"],
    "work_ms": ["{}ms of work"],
    "concurrency": ["{} concurrent"],
    "awaited_over_blocking": ["{} times the throughput"],
    "sync_over_blocking": ["{} times what a coroutine"],
    "blocking_p99_ms": ["p99 of {}ms", "{}ms at p99"],
    "blocking_lag_p99_ms": ["{}ms late", "lag of {}ms"],
    "awaited_lag_p99_ms": ["against {}ms"],
    "healthy_with_worse_p99": ["all {} of the healthy"],
    "invariant_min": ["between {} and"],
    "invariant_max": ["and {}"],
    "invariant_drift": ["factor of {}"],
    "concurrency_range": ["{}-fold range"],
    "awaited_growth": ["grows {}-fold"],
    "blocking_growth": ["grows {}-fold", "{}-fold, which is to say"],
    "smallest_fraction_blocking_ms": ["{}ms of blocking"],
    "e3_work_ms": ["out of {}ms"],
    "loss_low_pct": ["costs {} percent"],
    "loss_high_pct": ["and {} percent"],
    "low_concurrency": ["at {} concurrent requests"],
    "high_concurrency": ["percent at {}"],
    "quiet_lag_p99_ms": ["stays at {}ms"],
    "handler_p99_ms": ["reads {}ms"],
    "client_p99_ms": ["waited {}ms"],
    "middleware_p99_ms": ["middleware clock reads {}ms"],
    "blind_factor": ["factor of {}"],
    "healthy_factor": ["accurate to {}"],
    "live_throughput_drop": ["factor of {} on a real"],
    "apparatus_ceiling_rps": ["ceiling of {} rps"],
    "live_predicted_rps": ["predicted {} rps"],
}


def run(cmd: list[str], **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, check=False, **kwargs)


def measure_suite(skip_tests: bool) -> dict:
    junit, cov = ROOT / "junit.xml", ROOT / "coverage.json"
    if skip_tests:
        missing = [p.name for p in (junit, cov) if not p.exists()]
        if missing:
            raise SystemExit(f"--skip-tests given but {', '.join(missing)} not found")
    else:
        result = run([sys.executable, "-m", "pytest", f"--junitxml={junit}",
                      "--cov=event_loop_tax", "--cov-report=json", "-q"],
                     capture_output=True, text=True)
        if result.returncode != 0:
            print(result.stdout[-4000:], file=sys.stderr)
            raise SystemExit("test suite failed, refusing to publish metrics")
    suite = ET.parse(junit).getroot()
    node = suite if suite.tag == "testsuite" else suite.find("testsuite")
    totals = json.loads(cov.read_text())["totals"]
    return {"tests_total": int(node.get("tests", 0)) - int(node.get("skipped", 0)),
            "coverage_line_pct": int(totals["percent_covered"])}


def load_experiments() -> dict[str, dict]:
    payloads = {}
    for name in EXPERIMENTS:
        path = EXPERIMENT_DIR / f"{name}.json"
        if not path.exists():
            raise SystemExit(
                f"recorded experiment missing: {path.name}\n"
                "Timings are not regenerated by this script. Run `make bench`."
            )
        payloads[name] = json.loads(path.read_text())
    return payloads


def derive(suite: dict, exp: dict[str, dict]) -> dict:
    e1, e2 = exp["e1_four_shapes"], exp["e2_concurrency_sweep"]
    e3, e4 = exp["e3_how_little_is_too_much"], exp["e4_three_clocks"]

    metrics: dict = {
        **suite,
        "work_ms": e1["work_ms"],
        "concurrency": e1["concurrency"],
        "awaited_over_blocking": e1["throughput_gap_awaited_over_blocking"],
        "sync_over_blocking": e1["throughput_gap_sync_over_blocking"],
        "blocking_p99_ms": e1["blocking_p99_ms"],
        "blocking_lag_p99_ms": round(e1["blocking_lag_p99_ms"], 0),
        "awaited_lag_p99_ms": e1["awaited_lag_p99_ms"],
        "healthy_with_worse_p99": len(e1["healthy_shapes_with_worse_p99"]),
        "invariant_min": e2["invariant_min"],
        "invariant_max": e2["invariant_max"],
        "invariant_drift": e2["invariant_drift"],
        "concurrency_range": e2["concurrency_range"],
        "awaited_growth": int(e2["awaited_growth"]),
        "blocking_growth": e2["blocking_growth"],
        "e3_work_ms": e3["work_ms"],
        "smallest_fraction_blocking_ms": e3["smallest_fraction_blocking_ms"],
        "loss_low_pct": round(e3["loss_at_smallest_low_concurrency"] * 100, 1),
        "loss_high_pct": round(e3["loss_at_smallest_high_concurrency"] * 100, 1),
        "low_concurrency": e3["concurrencies"][0],
        "high_concurrency": e3["concurrencies"][-1],
        "quiet_lag_p99_ms": e3["quiet_lag_p99_ms"],
        "handler_p99_ms": e4["blocking_handler_p99_ms"],
        "client_p99_ms": e4["blocking_client_p99_ms"],
        "middleware_p99_ms": e4["blocking_middleware_p99_ms"],
        "blind_factor": e4["handler_clock_blind_factor"],
        "healthy_factor": e4["handler_clock_healthy_factor"],
        "live_throughput_drop": e4["live_throughput_drop"],
        "apparatus_ceiling_rps": round(e4["apparatus_ceiling_rps"], 0),
        "live_predicted_rps": round(e4["predicted_handler_rps"], 0),
    }

    for cell in e1["cells"]:
        key = cell["handler"]
        metrics[f"e1_{key}_rps"] = cell["rps"]
        metrics[f"e1_{key}_ceiling"] = cell["ceiling_rps"]
        metrics[f"e1_{key}_p99"] = cell["p99_ms"]
        metrics[f"e1_{key}_lag"] = cell["lag_p99_ms"]
        for suffix in ("rps", "ceiling", "p99", "lag"):
            ANCHORS.setdefault(f"e1_{key}_{suffix}", TABLE_ANCHOR)

    for cell in e2["cells"]:
        key = f"e2_{cell['handler']}_{cell['concurrency']}"
        metrics[key] = cell["rps"]
        ANCHORS.setdefault(key, TABLE_ANCHOR)
        if cell["handler"] == "async_blocking":
            metrics[f"{key}_inv"] = cell["rps_times_blocking_seconds"]
            ANCHORS.setdefault(f"{key}_inv", TABLE_ANCHOR)

    # The swept constants are metrics too. They appear in a published table, so leaving
    # them unregistered means the reverse check flags every row of the sweep, and
    # silencing that by hand is how a checker starts getting worked around.
    for fraction in e3["fractions"]:
        key = f"e3_fraction_{str(fraction).replace('.', '')}"
        metrics[key] = fraction
        ANCHORS.setdefault(key, TABLE_ANCHOR)

    for cell in e3["cells"]:
        tag = str(cell["blocking_fraction"]).replace(".", "")
        key = f"e3_{cell['concurrency']}_{tag}"
        metrics[key] = round(cell["retained"] * 100, 1)
        ANCHORS.setdefault(key, TABLE_ANCHOR)

    for cell in e4["cells"]:
        key = cell["shape"]
        metrics[f"e4_{key}_rps"] = cell["rps"]
        metrics[f"e4_{key}_handler"] = cell["handler_p99_ms"]
        metrics[f"e4_{key}_middleware"] = cell["middleware_p99_ms"]
        metrics[f"e4_{key}_client"] = cell["client_p99_ms"]
        for suffix in ("rps", "handler", "middleware", "client"):
            ANCHORS.setdefault(f"e4_{key}_{suffix}", TABLE_ANCHOR)

    return metrics


# Formatting is declared per metric rather than guessed from the key name. An earlier
# repository in this series inferred it from suffixes and printed a ratio as 33.6000
# because the key happened to end in _cost. A figure that renders two ways defeats the
# anchor mechanism entirely.
SCALAR_FORMATS = {
    "work_ms": "{:g}", "e3_work_ms": "{:g}",
    "awaited_over_blocking": "{:.1f}", "sync_over_blocking": "{:.1f}",
    "blocking_p99_ms": "{:.2f}", "blocking_lag_p99_ms": "{:.0f}",
    "awaited_lag_p99_ms": "{:.2f}",
    "invariant_min": "{:.4f}", "invariant_max": "{:.4f}", "invariant_drift": "{:.3f}",
    "blocking_growth": "{:.2f}",
    "smallest_fraction_blocking_ms": "{:g}",
    "loss_low_pct": "{:.1f}", "loss_high_pct": "{:.1f}",
    "quiet_lag_p99_ms": "{:.2f}",
    "handler_p99_ms": "{:.2f}", "client_p99_ms": "{:.2f}",
    "middleware_p99_ms": "{:.2f}",
    "blind_factor": "{:.1f}", "healthy_factor": "{:.2f}",
    "live_throughput_drop": "{:.1f}",
    "apparatus_ceiling_rps": "{:.0f}", "live_predicted_rps": "{:.0f}",
}


def display_strings(metrics: dict) -> dict[str, str]:
    out = {}
    for key, value in metrics.items():
        if key in SCALAR_FORMATS:
            out[key] = SCALAR_FORMATS[key].format(value)
        elif isinstance(value, int):
            out[key] = str(value)
        elif key.endswith("_inv"):
            out[key] = f"{value:.4f}"
        elif key.startswith("e2_"):
            # Throughput, always to one decimal, so the column reads consistently
            # whether a figure is in the hundreds or the tens of thousands.
            out[key] = f"{value:.1f}"
        elif key.startswith("e3_fraction_"):
            out[key] = f"{value:g}"
        elif key.startswith("e3_") or value >= 1000:
            out[key] = f"{value:.1f}"
        else:
            out[key] = f"{value:.2f}"
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description="Re-measure the deterministic figures.")
    parser.add_argument("--skip-tests", action="store_true")
    args = parser.parse_args()
    metrics = derive(measure_suite(args.skip_tests), load_experiments())
    METRICS_PATH.write_text(json.dumps({
        "metrics": metrics, "display": display_strings(metrics), "anchors": ANCHORS,
        "checked_documents": list(CHECKED_DOCUMENTS),
        "note": "suite figures are re-measured here; timings are read from the recorded "
                "run, because rerunning them changes them. The relationship between them "
                "is re-derived by tools/check_invariant.py on every verify.",
    }, indent=2) + "\n")
    print(f"wrote {METRICS_PATH} with {len(metrics)} metrics")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
